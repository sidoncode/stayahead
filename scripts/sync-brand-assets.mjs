// Syncs the "Stay Ahead visual identity" pack into the app.
//   assets/*.png, manifest, favicons, app icons -> public/
//   assets/logo-*.svg                           -> src/assets/brand/
//   icons/icon-*.svg                            -> src/components/icons.generated.ts
// SVGs ship a large C2PA <metadata> block; it is stripped on the way in.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pack = join(root, 'Stay Ahead visual identity')
const strip = (svg) => svg.replace(/<metadata>[\s\S]*?<\/metadata>/g, '').replace(/ xmlns:c2pa="[^"]*"/g, '')

const publicDir = join(root, 'public')
const brandDir = join(root, 'src/assets/brand')
mkdirSync(publicDir, { recursive: true })
mkdirSync(brandDir, { recursive: true })

for (const file of readdirSync(join(pack, 'assets'))) {
  const from = join(pack, 'assets', file)
  const isLogo = file.startsWith('logo-')
  const to = join(isLogo ? brandDir : publicDir, file)
  if (file.endsWith('.svg')) writeFileSync(to, strip(readFileSync(from, 'utf8')))
  else copyFileSync(from, to)
}

const icons = {}
for (const file of readdirSync(join(pack, 'icons')).sort()) {
  if (!file.startsWith('icon-') || !file.endsWith('.svg')) continue
  const svg = strip(readFileSync(join(pack, 'icons', file), 'utf8'))
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim()
  icons[file.slice(5, -4)] = inner
}

const names = Object.keys(icons)
writeFileSync(
  join(root, 'src/components/icons.generated.ts'),
  `// Generated by scripts/sync-brand-assets.mjs. Do not edit.\n` +
    `// 24px grid, 1.5px stroke, round caps/joins, currentColor.\n` +
    `export const ICONS = ${JSON.stringify(icons, null, 2)} as const\n\n` +
    `export type IconName = ${names.map((n) => `'${n}'`).join(' | ')}\n`,
)
console.log(`synced ${names.length} icons and brand assets`)
